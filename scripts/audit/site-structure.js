/**
 * scripts/audit/site-structure.js — Phase 1A / PART 2: Site Structure Map (READ-ONLY).
 * Builds a directory-depth histogram from the pages actually on disk, and
 * documents hub relationships / navigation / URL patterns based on the
 * shared header/footer nav emitted by scripts/generate-programmatic-pages.js
 * baseLayout() (grep-verified, see notes).
 */

const { allHtmlFiles, writeAuditJson } = require('./_lib.js');
const { classify, CATEGORY_LABELS, RULES } = require('./classify.js');

function urlForFile(relPath) {
  if (relPath === 'index.html') return '/';
  if (relPath.endsWith('/index.html')) return '/' + relPath.slice(0, -'index.html'.length);
  return '/' + relPath;
}

function depthOf(url) {
  return url.split('/').filter(Boolean).length;
}

function buildDepthHistogram(htmlFiles) {
  const hist = {};
  const samples = {};
  for (const f of htmlFiles) {
    const { category } = classify(f);
    if (category === 'template-source') continue;
    const url = urlForFile(f);
    const d = depthOf(url);
    hist[d] = (hist[d] || 0) + 1;
    if (!samples[d]) samples[d] = [];
    if (samples[d].length < 3) samples[d].push(url);
  }
  return Object.keys(hist)
    .map(Number)
    .sort((a, b) => a - b)
    .map((d) => ({ depth: d, count: hist[d], sampleUrls: samples[d] }));
}

