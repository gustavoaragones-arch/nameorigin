function buildUrlPatterns() {
  return RULES.filter((r) => r.category !== 'template-source').map((r) => ({
    category: r.category,
    label: CATEGORY_LABELS[r.category] || r.category,
    group: r.group,
    pattern: r.test.toString(),
  }));
}

